# train5.py - neural detail pass v5: our own multi-scale U-Net (sees whole faces / panels at once).
#
# Runs on the finished frame (after FSR 2), like v3. Layout (all convs 3x3, ReLU except the last):
#   input 2x2 pixel-unshuffle -> half res (12 ch)
#   half:  E0 12->A, E1 A->A
#   1/4:   D0 A->B stride 2, D1 B->B
#   1/8:   D2 B->B stride 2, D3 B->B
#   1/16:  D4 B->B stride 2, D5 B->B
#   1/8:   U0 up(D5)+D3 -> B, U1 B->B
#   1/4:   U2 up(U1)+D1 -> B, U3 B->B
#   half:  U4 up(U3)+E1 -> A, U5 A->A, OUT A->12 -> pixel-shuffle residual (full res RGB)
# "up" = nearest 2x, cropped to the skip's size (matches the game shader for odd sizes).
# Brightness guard (same in game): residual minus its 16x16 box mean (bilinear) -> local shading may
# change but no area gets brighter / darker overall; output within the input's 3x3 range widened by
# GM*range + GA, and 0..1.
# Usage: NN_A=16 NN_B=32 nnvenv/bin/python -I train5.py OUTPREFIX STEPS PAIRS.txt
import sys, os, random, time
import numpy as np, torch, torch.nn as nn, torch.nn.functional as F
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import train3 as T

dev = T.dev
A, B = int(os.environ.get('NN_A', 16)), int(os.environ.get('NN_B', 32))
GM, GA = float(os.environ.get('NN_GM', 0.6)), float(os.environ.get('NN_GA', 0.03))
# layer table: (name, src0, mode0, src1, mode1, cin, cout)  mode 0 same res, 1 stride 2, 2 up 2x; src -1 none
# tensor 0 = unshuffled input, tensor i+1 = output of layer i
X = int(os.environ.get('NN_EXTRA', 0))   # extra B->B convs at each deep level (v7+)
def build():
    L = []
    def add(nm, s0, m0, s1, m1, ci, co): L.append((nm, s0, m0, s1, m1, ci, co)); return len(L)   # returns tensor id
    t = add('E0', 0, 0, -1, 0, 12, A); e1 = add('E1', t, 0, -1, 0, A, A)
    t = add('D0', e1, 1, -1, 0, A, B); d1 = add('D1', t, 0, -1, 0, B, B)
    t = add('D2', d1, 1, -1, 0, B, B); d3 = add('D3', t, 0, -1, 0, B, B)
    for i in range(X): d3 = add('D3x', d3, 0, -1, 0, B, B)
    t = add('D4', d3, 1, -1, 0, B, B); d5 = add('D5', t, 0, -1, 0, B, B)
    for i in range(X): d5 = add('D5x', d5, 0, -1, 0, B, B)
    t = add('U0', d5, 2, d3, 0, 2 * B, B); t = add('U1', t, 0, -1, 0, B, B)
    for i in range(X): t = add('U1x', t, 0, -1, 0, B, B)
    t = add('U2', t, 2, d1, 0, 2 * B, B); t = add('U3', t, 0, -1, 0, B, B)
    t = add('U4', t, 2, e1, 0, B + A, A); t = add('U5', t, 0, -1, 0, A, A)
    add('OUT', t, 0, -1, 0, A, 12)
    return L
LAYERS = build()

def blur16(r):
    H, W = r.shape[-2:]
    m = F.avg_pool2d(r, 16, 16, ceil_mode=True)
    return F.interpolate(m, size=(H, W), mode='bilinear', align_corners=False)

PROT, PB0, PB1 = float(os.environ.get('NN_PROT', 0.9)), 0.12, 0.10
def busy8(x):
    # 8x8 mean (bilinear) of the input's local contrast = what the game reads from mip level 3
    H, W = x.shape[-2:]
    lo = -F.max_pool2d(-x, 3, 1, 1); hi = F.max_pool2d(x, 3, 1, 1)
    e = (hi - lo).amax(1, keepdim=True)
    return F.interpolate(F.avg_pool2d(e, 8, 8, ceil_mode=True), size=(H, W), mode='bilinear', align_corners=False)

def guard(x, r):
    # pattern guard (session 83): dense high-contrast areas (grates, vents) change less, so holes keep
    # their shape. NN_PROT=0 = the v5-v7 guard.
    r = r - blur16(r)
    lo = -F.max_pool2d(-x, 3, 1, 1); hi = F.max_pool2d(x, 3, 1, 1)
    k = 1 - PROT * ((busy8(x) - PB0) / PB1).clamp(0, 1) if PROT > 0 else 1
    m = GM * (hi - lo) * k + GA
    return torch.minimum(torch.maximum(x + k * r, lo - m), hi + m).clamp(0, 1)

class Net(nn.Module):
    def __init__(s):
        super().__init__()
        s.convs = nn.ModuleList(nn.Conv2d(l[5], l[6], 3, stride=2 if l[2] == 1 else 1, padding=1) for l in LAYERS)
        nn.init.zeros_(s.convs[-1].weight); nn.init.zeros_(s.convs[-1].bias)
    def residual(s, x):
        t = [F.pixel_unshuffle(x, 2)]
        for i, (nm, s0, m0, s1, m1, ci, co) in enumerate(LAYERS):
            h = t[s0]
            if s1 >= 0:
                k = t[s1]
                if m0 == 2: h = F.interpolate(h, scale_factor=2, mode='nearest')[..., :k.shape[2], :k.shape[3]]
                h = torch.cat([h, k], 1)
            h = s.convs[i](h)
            if i < len(LAYERS) - 1: h = F.relu(h)
            t.append(h)
        return F.pixel_shuffle(t[-1], 2)
    def forward(s, x): return guard(x, s.residual(x))

def export_header(net, path):
    with open(path, 'w') as f:
        f.write('// generated by neural/train5.py (U-Net)\n#define NN_UNET 1\n#define NN_LAYERS %d\n#define NN_C %d\n' % (len(LAYERS), max(A, B)))
        f.write('#define NN_GM %.6ff\n#define NN_GA %.6ff\n' % (GM, GA))
        f.write('#define NN_PB0 %.6ff\n#define NN_PB1 %.6ff\n#define NN_PROT %.6ff\n' % (PB0, PB1, PROT))   # guard used in training = game default
        for i, c in enumerate(net.convs):
            w = c.weight.detach().cpu().float().numpy(); b = c.bias.detach().cpu().float().numpy()
            f.write('static const float nn_w%d[%d] = {%s};\n' % (i, w.size, ','.join('%.8g' % v for v in w.ravel())))
            f.write('static const float nn_b%d[%d] = {%s};\n' % (i, b.size, ','.join('%.8g' % v for v in b)))
        n = len(LAYERS)
        f.write('static const float *const nn_W[NN_LAYERS] = {%s};\nstatic const float *const nn_B[NN_LAYERS] = {%s};\n' %
                (','.join('nn_w%d' % i for i in range(n)), ','.join('nn_b%d' % i for i in range(n))))
        for k, nm in ((1, 'src0'), (2, 'mode0'), (3, 'src1'), (4, 'mode1'), (5, 'cin'), (6, 'cout')):
            f.write('static const int nn_%s[NN_LAYERS] = {%s};\n' % (nm, ','.join(str(l[k]) for l in LAYERS)))

class VGGLoss(nn.Module):
    # perceptual loss: compare texture features (VGG16 relu1_2..relu4_3) instead of exact pixels
    def __init__(s):
        super().__init__()
        import torchvision
        f = torchvision.models.vgg16(weights=torchvision.models.VGG16_Weights.IMAGENET1K_V1).features[:23].eval()
        for p in f.parameters(): p.requires_grad_(False)
        s.f = f; s.cut = (3, 8, 15, 22)
        s.register_buffer('mu', torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)); s.register_buffer('sd', torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1))
    def forward(s, o, g):
        x, y, l = (o - s.mu) / s.sd, (g - s.mu) / s.sd, 0
        for i, m in enumerate(s.f):
            x, y = m(x), m(y)
            if i in s.cut: l = l + (x - y).abs().mean()
        return l

def scale_aug(a, g):
    # the remaster tiles are at the game's 4K pixel scale; also show 1440p / 1080p scale content
    s = random.choice((1, 1, 1, 0.75, 0.5))
    if s == 1: return a, g
    p = a.shape[-1]; q = int(p * s) // 16 * 16
    return F.interpolate(a, size=(q, q), mode='area'), F.interpolate(g, size=(q, q), mode='area')

if __name__ == '__main__':
    out, steps, pairs = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    P = T.load_pairs(pairs); random.seed(1); random.shuffle(P)
    nval = max(2, len(P) // 10); val, tr = P[:nval], P[nval:]
    net, crit = Net().to(dev), T.Critic().to(dev)
    if os.environ.get('NN_INIT'): net.load_state_dict(torch.load(os.environ['NN_INIT'], map_location=dev)); print('init from', os.environ['NN_INIT'], flush=True)   # v9: fine-tune
    print(f'{len(tr)} train / {len(val)} val pairs on {dev}, A={A} B={B}, guard {GM}/{GA}, {sum(p.numel() for p in net.parameters())} weights', flush=True)
    lr = float(os.environ.get('NN_LR', 5e-4))
    opt = torch.optim.Adam(net.parameters(), lr); optc = torch.optim.Adam(crit.parameters(), 2e-4, betas=(0.5, 0.999))
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, lr, total_steps=steps)
    random.seed(2); va, vb = T.batch_pairs(val, 16, 256); vi = T.degrade(va); vm = T.keep_mask(va, vb)
    print(f'val: {vm.mean().item()*100:.0f}% of pixels kept (rest = redrawn by the remaster)', flush=True)
    vw = float(os.environ.get('NN_VGG', 0)); vgg = VGGLoss().to(dev) if vw > 0 else None
    adv = float(os.environ.get('NN_ADV', 0.02)); adv_from = steps // 4; t0 = time.time()
    bs, ps_ = int(os.environ.get('NN_BS', 12)), int(os.environ.get('NN_PATCH', 256))
    for it in range(steps):
        a, g = T.batch_pairs(tr, bs, ps_); a, g = scale_aug(a, g)
        with torch.no_grad(): x = T.degrade(a); m = T.keep_mask(a, g)
        o = net(x); l = T.recon_m(o, g, m)
        if vgg is not None: l = l + vw * vgg(o * m + g * (1 - m), g)    # redrawn pixels don't count
        if it >= adv_from: l = l + adv * F.softplus(-crit(o)).mean()
        opt.zero_grad(); l.backward(); opt.step(); sched.step()
        if it >= adv_from - 500:
            dl = F.softplus(-crit(g)).mean() + F.softplus(crit(o.detach())).mean()
            optc.zero_grad(); dl.backward(); optc.step()
        if it % 1000 == 0 or it == steps - 1:
            with torch.no_grad():
                o = net(vi)
                def ps(z): return (10 * torch.log10(1 / (((z - vb) ** 2) * vm).sum() * (3 * vm.sum()))).item()
                print(f'it {it} | masked PSNR in {ps(vi):.2f} net {ps(o):.2f} | detail remaster {T.hf_spec(vb).mean().item():.3f} game {T.hf_spec(va).mean().item():.3f} in {T.hf_spec(vi).mean().item():.3f} net {T.hf_spec(o).mean().item():.3f} | brightness game {va.mean():.4f} net {o.mean():.4f} | {time.time()-t0:.0f}s', flush=True)
            if it % 5000 == 0 and it: torch.save(net.state_dict(), out + '.pt')
    torch.save(net.state_dict(), out + '.pt'); export_header(net, out + '_weights.h'); print('saved', out)
