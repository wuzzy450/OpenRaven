#!/usr/bin/env python3
# Generates gl_thunks.c: a SysV-ABI wrapper for every GL/GLU function in the
# MSYS2 headers (gl.h, glext.h, glu.h). Each wrapper resolves the real Windows
# function on first call (opengl32 / glu32 / wglGetProcAddress) and forwards;
# the compiler does the SysV -> MS x64 argument conversion.
#
# usage: python gen_gl.py <msys2 include/GL dir> > gl_thunks.c
import re
import sys

inc = sys.argv[1]
proto = re.compile(r'^(?:GLAPI|WINGDIAPI)\s+(.+?)\s*\bAPIENTRY\s+(\w+)\s*\((.*)\)\s*;')
funcs = {}
for header in ("gl.h", "glext.h", "glu.h"):
    for line in open(f"{inc}/{header}", encoding="latin-1"):
        m = proto.match(line.strip())
        if not m:
            continue
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
        if name in funcs:
            continue
        funcs[name] = (ret, args)

# Callbacks are called by the driver with the MS ABI; these need hand-written
# wrappers (see shim_glx.c), so they are left out here.
skip = {"glDebugMessageCallback", "glDebugMessageCallbackARB", "glDebugMessageCallbackAMD",
        "gluTessCallback", "gluQuadricCallback", "gluNurbsCallback"}


def arg_names(args):
    if args in ("", "void"):
        return [], ""
    names, decls = [], []
    for i, a in enumerate(a.strip() for a in args.split(",")):
        m = re.match(r"^(.*?)(\w+)\s*(\[[^\]]*\])?$", a)
        base, nm, arr = m.group(1).strip(), m.group(2), m.group(3) or ""
        if not base or nm in ("GLenum", "GLint", "GLuint", "GLfloat", "GLdouble", "GLboolean"):
            # unnamed parameter: the whole thing is the type
            base, nm, arr = a, f"a{i}", ""
        nm = f"{nm}_"  # avoid clashes with typedef names
        names.append(nm)
        decls.append(f"{base} {nm}{arr}")
    return names, ", ".join(decls)


out = [
    "// Generated by gen_gl.py - do not edit.",
    "#include <windows.h>",
    "#include <GL/gl.h>",
    "#include <GL/glext.h>",
    "#include <GL/glu.h>",
    '#include "shim.h"',
    "void *gl_resolve(const char *name);",
    "",
]
table = []
for name, (ret, args) in sorted(funcs.items()):
    if name in skip:
        continue
    names, decl = arg_names(args)
    proto_args = decl if decl else "void"
    out.append(f"typedef {ret} (APIENTRY *t_{name})({proto_args});")
    out.append(f"static t_{name} p_{name};")
    call = f"p_{name}({', '.join(names)})"
    body = f"if (!p_{name}) p_{name} = (t_{name})gl_resolve(\"{name}\"); "
    body += f"{'return ' if ret != 'void' else ''}{call};"
    out.append(f"static SV {ret} w_{name}({proto_args}) {{ {body} }}")
    table.append(f'    {{"{name}", (void *)w_{name}}},')
out.append("const shim_entry shims_gl[] = {")
out += table
out.append("    {NULL, NULL},")
out.append("};")
print("\n".join(out))
